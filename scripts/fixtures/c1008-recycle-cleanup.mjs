import fs from 'node:fs';
import cp from 'node:child_process';
import os from 'node:os';
const root=process.argv[2];
if(!/^\/tmp\/c1008-real-[A-Za-z0-9]+$/.test(root||'')||fs.lstatSync(root).isSymbolicLink())throw Error('FixtureRootRefused');
const ledger=JSON.parse(fs.readFileSync(root+'/ownership.json','utf8'));
const prefix=ledger.prefix,label='io.antiphon.c1008-real';
if(ledger.schema!==1||!/^c1008rd[0-9a-f]{16}$/.test(prefix)||! /^[0-9a-f]{40}$/.test(ledger.source))throw Error('FixtureLedgerRefused');
const d=(...args)=>cp.execFileSync('docker',args,{encoding:'utf8',timeout:30000}).trim();
if(!fs.existsSync('/.dockerenv')||d('info','--format','{{.Name}}')!==os.hostname())throw Error('SiblingDaemonRefused');
const containers=d('ps','-aq','--no-trunc','--filter','label='+label+'='+prefix).split('\n').filter(Boolean).map(id=>JSON.parse(d('inspect',id))[0]);
if(containers.some(c=>c.Config.Labels[label]!==prefix))throw Error('ContainerOwnership');
const volumes=d('volume','ls','-q','--filter','label='+label+'='+prefix).split('\n').filter(Boolean).map(name=>JSON.parse(d('volume','inspect',name))[0]);
if(volumes.some(v=>!v.Name.startsWith(prefix)||v.Labels[label]!==prefix))throw Error('VolumeOwnership');
const projects=new Set(fs.readdirSync(root).filter(n=>n.startsWith(prefix)&&/^c1008rd[0-9a-f]{16}c[0-9a-f]{8}$/.test(n)).flatMap(n=>[n+'main',n+'temp']));
const networks=d('network','ls','-q','--filter','label=com.docker.compose.project').split('\n').filter(Boolean).map(id=>JSON.parse(d('network','inspect',id))[0]).filter(n=>projects.has(n.Labels['com.docker.compose.project']));
const imageCheck=cp.spawnSync('docker',['image','inspect',prefix+':fixture'],{encoding:'utf8',timeout:30000});
let image;
if(imageCheck.status===0){image=JSON.parse(imageCheck.stdout)[0];if(image.Config.Labels?.[label]!==prefix)throw Error('ImageOwnership');}
else if(imageCheck.status!==1||!imageCheck.stderr.toLowerCase().includes('no such image'))throw Error('ImageCensusUnknown');
const evidence={...ledger,containers:containers.map(c=>c.Id),volumes:volumes.map(v=>v.Name),networks:networks.map(n=>n.Id),image:image?.Id,phase:'before'};
fs.writeFileSync(root+'/recovery.json',JSON.stringify(evidence,null,2));
for(const c of containers)d('rm','-f','--',c.Id);
for(const v of volumes)d('volume','rm','--',v.Name);
for(const n of networks)d('network','rm',n.Id);
if(image)d('image','rm',prefix+':fixture');
if(d('ps','-aq','--filter','label='+label+'='+prefix)||d('volume','ls','-q','--filter','label='+label+'='+prefix))throw Error('FixtureResidue');
if(image&&cp.spawnSync('docker',['image','inspect',prefix+':fixture'],{encoding:'utf8'}).status===0)throw Error('ImageResidue');
const currentNetworks=new Set(d('network','ls','-q','--no-trunc').split('\n'));
if(networks.some(n=>currentNetworks.has(n.Id)))throw Error('NetworkResidue');
fs.writeFileSync(root+'/recovery.json',JSON.stringify({...evidence,phase:'absence-verified'},null,2));
console.log('C1008_RECOVERY containers='+containers.length+' volumes='+volumes.length+' networks='+networks.length+' image='+(image?1:0)+' absent');
