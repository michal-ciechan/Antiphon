// Storybook screenshot suite — documentation + drastic-breakage tripwire.
//
// For every story in the Storybook index it renders the story iframe (NO manager chrome — the
// toolbar/sidebar never appear, and component stories carry no app navbar by design) and writes a
// PNG under docs/ui-screenshots/. The images double as visual documentation of the UI and as a
// quick "is something drastically broken?" check: regenerate and eyeball the git diff.
//
// Determinism: stories seed their data from the CONTRACT fixtures under
// src/test/fixtures/contract/ (captured from the real backend by ContractSnapshotTests), CSS
// animations/caret are disabled, and the story iframe is a fixed 1440×900 viewport.
//
// Browser: connects over CDP to the already-running Edge (BU_CDP_URL / localhost:9222 — the same
// instance browser-harness drives) via playwright-core, so no browser download is needed.
// Storybook: uses a running dev server on 17209, or boots one itself (--ci) and kills it after.
//
// Usage:  node scripts/storybook-screenshots.mjs [story-id-substring ...]

import { spawn } from 'node:child_process'
import { mkdirSync, writeFileSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'
import { chromium } from 'playwright-core'

const clientDir = join(dirname(fileURLToPath(import.meta.url)), '..')
const outDir = join(clientDir, '..', 'docs', 'ui-screenshots')
const storybookUrl = process.env.STORYBOOK_URL ?? 'http://localhost:17209'
const cdpUrl = process.env.BU_CDP_URL ?? 'http://localhost:9222'
const filters = process.argv.slice(2)

async function isUp(url) {
  try {
    const r = await fetch(url, { signal: AbortSignal.timeout(2000) })
    return r.ok
  } catch {
    return false
  }
}

async function main() {
  let storybookChild = null
  if (!(await isUp(`${storybookUrl}/index.json`))) {
    console.log('Storybook not running — booting one (this takes ~30s)…')
    storybookChild = spawn(
      process.platform === 'win32' ? 'npx.cmd' : 'npx',
      ['storybook', 'dev', '-p', '17209', '--no-open', '--ci'],
      { cwd: clientDir, stdio: 'ignore', shell: process.platform === 'win32' },
    )
    const deadline = Date.now() + 120_000
    while (Date.now() < deadline && !(await isUp(`${storybookUrl}/index.json`)))
      await new Promise((r) => setTimeout(r, 2000))
    if (!(await isUp(`${storybookUrl}/index.json`))) throw new Error('Storybook did not come up')
  }

  const index = await (await fetch(`${storybookUrl}/index.json`)).json()
  let stories = Object.values(index.entries).filter((e) => e.type === 'story')
  if (filters.length > 0)
    stories = stories.filter((s) => filters.some((f) => s.id.toLowerCase().includes(f.toLowerCase())))
  console.log(`${stories.length} stories to capture`)

  const browser = await chromium.connectOverCDP(cdpUrl)
  const context = browser.contexts()[0] ?? (await browser.newContext())
  const page = await context.newPage()
  await page.setViewportSize({ width: 1440, height: 900 })

  mkdirSync(outDir, { recursive: true })
  const manifest = []
  for (const story of stories) {
    const url = `${storybookUrl}/iframe.html?viewMode=story&id=${story.id}`
    await page.goto(url, { waitUntil: 'networkidle' })
    // Freeze motion so screenshots are stable run to run.
    await page.addStyleTag({
      content: '*,*::before,*::after{animation:none!important;transition:none!important;caret-color:transparent!important}',
    })
    // Monaco (diff views) finishes layout after load — wait for its content when present.
    await page
      .waitForSelector('.monaco-editor .view-lines', { timeout: 5000 })
      .catch(() => {})
    await page.waitForTimeout(500)
    const file = join(outDir, `${story.id}.png`)
    // NOTE: no animations:'disabled' — Playwright's animation freezing hangs on Monaco's rAF
    // loop; the injected CSS above is what actually stabilizes the frame.
    try {
      await page.screenshot({ path: file, fullPage: true, timeout: 15000 })
    } catch {
      // Some stories keep repainting (spinners); a viewport-clipped shot still documents them.
      await page.screenshot({ path: file, timeout: 15000 })
    }
    manifest.push({ id: story.id, title: story.title, name: story.name, file: `${story.id}.png` })
    console.log(`  ✓ ${story.id}`)
  }
  await page.close()

  // The index is every story Storybook knows about, whether or not this run captured it. Writing
  // the manifest from `manifest` alone would silently delete every other entry on a filtered run —
  // the README would then claim the suite is three screenshots when it is thirty.
  const allStories = Object.values(index.entries).filter((e) => e.type === 'story')
  const readme = [
    '# UI screenshots',
    '',
    'Generated by `npm run screenshots` (client/scripts/storybook-screenshots.mjs) from Storybook',
    'stories whose data comes from the backend-contract fixtures',
    '(`client/src/test/fixtures/contract/`, captured by `ContractSnapshotTests`).',
    'Regenerate after UI changes and review the image diff — a drastic rendering break shows up',
    'here before anyone opens the app.',
    '',
    ...allStories.map((s) => `## ${s.title} — ${s.name}\n\n![${s.id}](./${s.id}.png)\n`),
  ].join('\n')
  writeFileSync(join(outDir, 'README.md'), readme)
  console.log(`Wrote ${manifest.length} screenshots + README to docs/ui-screenshots/`)

  if (storybookChild) storybookChild.kill()
  process.exit(0)
}

main().catch((err) => {
  console.error(err)
  process.exit(1)
})
