using System.Security.Cryptography;
using System.Text;
using Shouldly;
using TUnit.Core;

namespace Antiphon.Agents.Pty.Tests;

[Category("Unit")]
public class CodexV0160FixtureTests
{
    [Test]
    public void C907_raw_capture_replays_the_running_frame()
    {
        var bytes = File.ReadAllBytes(PathFor("turn-prefix.ansi"));
        var recorded = File.ReadAllLines(PathFor("chunks.txt")).Select(int.Parse).ToArray();
        recorded.Sum().ShouldBe(bytes.Length, "C907 recorded reads cover the consumed prefix");
        foreach (var (name, end, working) in new[]
                 { ("idle", 3945, false), ("running", 6740, true), ("done", 9621, false) })
        {
            var frozen = File.ReadAllText(PathFor(name + ".txt"));
            foreach (var mode in new[] { "whole", "recorded", "single-byte" })
            {
                var screen = new TerminalScreen(120, 30);
                var decoder = new UTF8Encoding(false, true).GetDecoder();
                var offset = 0;
                var sizes = mode switch
                {
                    "whole" => new[] { end },
                    "recorded" => recorded,
                    _ => Enumerable.Repeat(1, end)
                };
                foreach (var size in sizes)
                {
                    var count = Math.Min(size, end - offset);
                    var chars = new char[Encoding.UTF8.GetMaxCharCount(count)];
                    var used = decoder.GetChars(bytes, offset, count, chars, 0, offset + count == end);
                    screen.Feed(new string(chars, 0, used));
                    offset += count;
                    if (offset == end) break;
                }
                offset.ShouldBe(end, $"C907 {name}/{mode} complete prefix");
                screen.GetScreenText().ShouldBe(frozen, $"C907 {name}/{mode} independently frozen grid");
                CodexWorkingIndicator.IsVisible(screen.GetScreenText()).ShouldBe(working,
                    $"C907 {name}/{mode} captured working verdict");
            }
        }
    }

    [Test]
    public void C907_fixture_payloads_match_recorded_provenance()
    {
        foreach (var (name, hash) in new[]
        {
            ("idle.txt", "78e3caf57049ecc5c093b772c07a179a6088322c3d68726ca47fa66445db987e"),
            ("running.txt", "34fa58f2e96838318e67628b01e2df02b987a1de2eb303df2d8826bcbb535dd0"),
            ("done.txt", "78c8411e4f1ece0085969d5205b44184ffe865733938cd1946f6de7e4a712db8"),
            // Prefix and recorded-read hashes are copied from capture curation, not generated by replay.
            ("turn-prefix.ansi", "362830f2f97af513e58161a8336e3ef1043c21d678a37025e4d40251084faaea"),
            ("chunks.txt", "cba78b081a7f8457b34b573ea9f658691c6f56f5d243ec00c0f67cced20d6d0a")
        })
        {
            var bytes = File.ReadAllBytes(PathFor(name));
            Convert.ToHexString(SHA256.HashData(bytes)).ToLowerInvariant().ShouldBe(hash,
                $"C907 {name} captured payload digest");
        }
        foreach (var frame in new[] { CodexStartupFixtures.V0160Idle, CodexStartupFixtures.V0160Running,
                     CodexStartupFixtures.V0160Done })
        {
            frame.Split('\n').Length.ShouldBe(30, "C907 full grid includes trailing blank rows");
            frame.Contains("--- payload ---", StringComparison.Ordinal)
                .ShouldBeFalse("C907 metadata is outside parser input");
            frame.Contains("SHA-256", StringComparison.Ordinal)
                .ShouldBeFalse("C907 provenance is outside parser input");
        }
    }

    private static string PathFor(string suffix) =>
        Path.Combine(CodexStartupFixtures.DirectoryPath, "v0160-" + suffix);
}
