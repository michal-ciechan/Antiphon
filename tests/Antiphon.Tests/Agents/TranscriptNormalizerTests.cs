    // The compact-boundary fixture is the single source of truth for the record shape (captured
    // from real claude by ClaudeCompactionCanaryTests; fakeclaude mirrors it).
    private static string CompactBoundaryFixtureLine() =>
        File.ReadLines(Path.Combine(AppContext.BaseDirectory, "Agents", "Fixtures", "compact-boundary.jsonl"))
            .First(l => !string.IsNullOrWhiteSpace(l));

    [Test]
    public void Compact_boundary_line_normalizes_to_CompactBoundary_kind()
    {
        var parts = TranscriptNormalizer.Normalize(CompactBoundaryFixtureLine());

        var part = parts.ShouldHaveSingleItem();
        part.Kind.ShouldBe(TranscriptKinds.CompactBoundary);
        part.Text.ShouldBe("Context compacted (manual)");
        part.Uuid.ShouldNotBeNull();
        part.Timestamp.ShouldNotBeNull();
    }

    // At the NORMALIZER level only: no TurnEnd part, no StopReason. The working/idle rules DO rank
    // a manual boundary as a turn end (CARD-0041) — they key on the "(manual)" trigger in the text
    // pinned above, not on a stop reason. Both statements are true and neither replaces the other.
    [Test]
    public void Compact_boundary_is_not_a_turn_end()
    {
        var parts = TranscriptNormalizer.Normalize(CompactBoundaryFixtureLine());

        parts.ShouldNotContain(p => p.Kind == TranscriptKinds.TurnEnd);
        parts.Single().StopReason.ShouldBeNull();
    }

    // CARD-0041: the working rules read the TRIGGER out of the boundary's normalized text, so the
    // normalizer↔rule seam is load-bearing in both directions — a boundary that lost its trigger
    // would silently stop ending turns, and an auto boundary that gained "(manual)" would end them
    // when it must not. The fixture is the manual one; the auto shape is asserted alongside.
    [Test]
    public void Manual_and_auto_boundaries_are_distinguishable_by_the_working_rules()
    {
        var manual = TranscriptNormalizer.Normalize(CompactBoundaryFixtureLine()).ShouldHaveSingleItem();
        TranscriptKinds.IsManualCompactBoundary(manual.Kind, manual.Text).ShouldBeTrue();

        const string autoLine =
            """{"type":"system","subtype":"compact_boundary","uuid":"u-auto","timestamp":"2026-08-11T10:54:04.124Z","compactMetadata":{"trigger":"auto","preTokens":1000,"postTokens":100}}""";
        var auto = TranscriptNormalizer.Normalize(autoLine).ShouldHaveSingleItem();
        auto.Text.ShouldBe("Context compacted (auto)");
        TranscriptKinds.IsManualCompactBoundary(auto.Kind, auto.Text)
            .ShouldBeFalse("an auto compaction lands MID-turn — it must never rank as a turn end");
    }

    // The other half of CARD-0041: compaction's synthetic continuation record. It normalizes to a
    // plain UserPrompt (nothing structural survives), which is exactly why the rule matches by text.
    [Test]
    public void Compaction_continuation_record_normalizes_to_an_excludable_user_prompt()
    {
        const string line =
            """{"type":"user","uuid":"u-cont","timestamp":"2026-08-11T10:53:54.816Z","isCompactSummary":true,"message":{"role":"user","content":"This session is being continued from a previous conversation that ran out of context. The conversation is summarized below:\nAnalysis: ..."}}""";

        var part = TranscriptNormalizer.Normalize(line).ShouldHaveSingleItem();
        part.Kind.ShouldBe(TranscriptKinds.UserPrompt);
        TranscriptKinds.IsCompactionContinuationPrompt(part.Kind, part.Text).ShouldBeTrue();
    }

