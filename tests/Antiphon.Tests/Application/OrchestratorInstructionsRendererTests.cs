    [Test]
    public void Render_is_deterministic_and_version_is_the_body_hash()
    {
        var snapshot = Sample();
        var first = OrchestratorInstructionsRenderer.Render(snapshot);
        var second = OrchestratorInstructionsRenderer.Render(snapshot);
