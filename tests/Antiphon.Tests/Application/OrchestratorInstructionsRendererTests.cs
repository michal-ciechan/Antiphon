    [Test]
    [Arguments("\n")]
    [Arguments("\r\n")]
    public void Unknown_matrix_details_keep_the_byte_cap_and_matrix_first_elision(string lineEnding)
    {
        const string unknown = "unknown (chain read failed)";
        var roles = Antiphon.Server.Application.Services.ComplexityRoutingService.RoutableRoles;
        var snapshot = Sample() with
        {
            Matrix = new MatrixSection("Medium", roles.Select(role => new MatrixInstructionRow(
                role.ToString(), unknown, unknown, unknown, unknown, unknown)).ToArray()),
        };
        var body = OrchestratorInstructionsRenderer.Render(snapshot);
        body.ShouldContain("  Plan: effective unknown (chain read failed) via unknown (chain read failed)");
        foreach (var line in Lines(body, lineEnding).Where(line => line.StartsWith("- ", StringComparison.Ordinal)
                     || line.StartsWith("  ", StringComparison.Ordinal)))
        {
            Encoding.UTF8.GetByteCount(line).ShouldBeLessThanOrEqualTo(160);
            line.ShouldNotContain("\uFFFD");
        }
        var cap = Encoding.UTF8.GetByteCount(body) - 1;
        var fitted = OrchestratorInstructionsRenderer.Render(snapshot, cap);
        Encoding.UTF8.GetByteCount(fitted).ShouldBeLessThanOrEqualTo(cap);
        fitted.ShouldContain("… 14 rows: GET /api/complexity-chains");
        fitted.ShouldNotContain("  Plan:");
        fitted.ShouldContain("Antiphon CARD-0822 Code");
        fitted.ShouldNotContain("more: GET /api/routing-pins");

        const string combined = "unknown (stage pin, chain, chain metadata, standing agent, availability read failed)";
        var worst = snapshot with
        {
            Matrix = new MatrixSection("Medium", roles.Select(role => new MatrixInstructionRow(
                role.ToString(), combined, combined, combined, combined, combined)).ToArray()),
        };
        var worstBody = OrchestratorInstructionsRenderer.Render(worst);
        worstBody.ShouldContain("  Plan: effective " + combined);
        worstBody.ShouldContain("  Plan: source " + combined);
        worstBody.ShouldNotContain("+2");
        foreach (var line in Lines(worstBody, lineEnding).Where(line => line.StartsWith("- ", StringComparison.Ordinal)
                     || line.StartsWith("  ", StringComparison.Ordinal)))
        {
            Encoding.UTF8.GetByteCount(line).ShouldBeLessThanOrEqualTo(160);
            line.ShouldNotContain("\uFFFD");
        }
        var worstCap = Encoding.UTF8.GetByteCount(worstBody) - 1;
        var worstFitted = OrchestratorInstructionsRenderer.Render(worst, worstCap);
        Encoding.UTF8.GetByteCount(worstFitted).ShouldBeLessThanOrEqualTo(worstCap);
        worstFitted.ShouldContain("… 14 rows: GET /api/complexity-chains");
        worstFitted.ShouldContain("Antiphon CARD-0822 Code");
        worstFitted.ShouldNotContain("  Plan:");
        worstFitted.ShouldNotContain("more: GET /api/routing-pins");
    }

    [Test]
    [Arguments("\n")]
    [Arguments("\r\n")]
    public void The_matrix_section_is_bounded_per_line_and_elided_in_place_under_pressure(string lineEnding)
    {
        string[] roles = ["Investigate", "Plan", "TestDesign", "Code", "Mutation", "Review", "Debug",
            "Coverage", "Docs", "Commit", "Test", "Deploy", "Merge", "Custom"];
        var candidates = string.Join(", ", Enumerable.Repeat("ClaudeCode/Frontier (fable)", 8));
        var snapshot = Sample() with
        {
            Matrix = new MatrixSection("Medium", roles.Select(role => new MatrixInstructionRow(
                role, candidates, candidates, candidates, "ClaudeCode/High (opus)", "stage pin")).ToArray()),
        };
        var body = OrchestratorInstructionsRenderer.Render(snapshot);
        foreach (var role in roles)
        {
            var matches = Lines(body, lineEnding).Where(line => line.StartsWith($"- {role}:", StringComparison.Ordinal)).ToArray();
            matches.Length.ShouldBe(1, $"matrix row {role}");
            var line = matches.Single();
            Encoding.UTF8.GetByteCount(line).ShouldBeLessThanOrEqualTo(160);
            line.ShouldContain("Hard ClaudeCode/Frontier (fable), ClaudeCode/Frontier (fable), ClaudeCode/Frontier (fable), +5");
            line.ShouldEndWith("…");
            line.ShouldNotContain("\uFFFD");
        }
        var cap = Encoding.UTF8.GetByteCount(body) - 1;
        var fitted = OrchestratorInstructionsRenderer.Render(snapshot, cap);
        Encoding.UTF8.GetByteCount(fitted).ShouldBeLessThanOrEqualTo(cap);
        var pointer = fitted.IndexOf("… 14 rows: GET /api/complexity-chains", StringComparison.Ordinal);
        pointer.ShouldBeGreaterThan(fitted.IndexOf("## 5. Role × complexity matrix", StringComparison.Ordinal));
        pointer.ShouldBeLessThan(fitted.IndexOf("## 6. Routing pins", StringComparison.Ordinal));
        fitted.ShouldNotContain("- Plan:");
        fitted.ShouldContain("Antiphon CARD-0822 Code");
        fitted.ShouldNotContain("more: GET /api/routing-pins");
        fitted.ShouldNotContain("more: GET /api/model-availability");
    }

    // A line terminator is outside the 160-byte content budget. Exercise both
    // newline conventions on every host, including CRLF on Linux.
    private static string[] Lines(string body, string lineEnding) =>
        body.ReplaceLineEndings(lineEnding).Split(["\r\n", "\n"], StringSplitOptions.None);

