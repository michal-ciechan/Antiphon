                new RoleInstructionRow("Review", 2, "Frontier", null, null),
            ]),
        Runners:
        [
            new RunnerInstructionRow("desktop", "windows", true, 2, 2, "configured", false, false, ["pty"], Occupied: 1, ObservedAt: "2026-10-10T00:00:00Z"),
            new RunnerInstructionRow("server2", "linux", true, 10, 10, "declared", false, false, ["pty"], Occupied: 3, ObservedAt: "2026-10-10T00:00:00Z"),
        ],
        Defaults: new RunnerDefaultsSection(2, "Human", "server2", [new KindDefaultInstruction("ClaudeCode", "server2")], "operator moved the default"),
        Holds: [new HoldInstructionRow("ClaudeCode", "fable", "Manual", "2099-01-01T00:00:00Z", "session limit")],
        Pins:
        [
            new PinInstructionRow(true, null, null, "Code", ["opus"], ["fable"], "require", "human", null, null, "stage pin", DateTimeOffset.Parse("2026-10-01T00:00:00Z")),
            new PinInstructionRow(false, "Antiphon", "CARD-0822", "Code", ["opus"], [], "prefer", "human", null, null, "card pin", DateTimeOffset.Parse("2026-10-02T00:00:00Z")),
        ],
        Levels:
        [
            new LevelInstructionRow("ClaudeCode", "Frontier", "fable"),
            new LevelInstructionRow("ClaudeCode", "High", "opus"),
            new LevelInstructionRow("ClaudeCode", "Medium", "sonnet"),
            new LevelInstructionRow("ClaudeCode", "Low", "haiku"),
            new LevelInstructionRow("Codex", "Frontier", "gpt-6-astra"),
            new LevelInstructionRow("Grok", "High", "grok-4.7"),
        ],
        StandingLines: ["prefer the live file"]);
}
